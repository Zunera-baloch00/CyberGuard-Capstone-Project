def main():
    if len(sys.argv) != 3:
        print(
            "Usage: python3 ai_report.py "
            "<scanner_results.txt> <output.html>"
        )
        return 2

    source = Path(sys.argv[1])
    output = Path(sys.argv[2])

    if not source.is_file():
        print(f"[!] Scanner results file not found: {source}")
        return 2

    if not API_KEY:
        print("[!] GEMINI_API_KEY is not set in this terminal.")
        return 2

    output.parent.mkdir(parents=True, exist_ok=True)

    raw = source.read_text(encoding="utf-8", errors="replace")
    evidence = compact_evidence(raw)

    match = re.search(
        r"(?:target|domain|ip address)\s*[:=]\s*(\S+)",
        raw,
        re.IGNORECASE,
    )
    target = match.group(1) if match else "See scanner evidence"

    print(f"[+] Preparing evidence for {MODEL}...")
    print(f"[+] Original evidence: {len(raw):,} characters")
    print(f"[+] Compact evidence: {len(evidence):,} characters")

    try:
        prompt = report_prompt(evidence)
        report = None

        for attempt in range(MAX_RETRIES + 1):
            try:
                print("[+] Requesting AI-generated HTML report...")
                generated, finish = call_gemini(prompt)
                generated = normalize_html(generated)

                if is_complete_html(generated):
                    report = generated
                    break

                print(
                    "[!] Gemini returned incomplete HTML. "
                    f"Finish reason: {finish}"
                )
                print("[+] Asking Gemini to repair the report...")
                report = repair_html(generated)
                break

            except urllib.error.HTTPError as exc:
                details = exc.read().decode("utf-8", errors="replace")

                if exc.code not in (429, 500, 502, 503, 504):
                    raise RuntimeError(
                        f"Gemini HTTP {exc.code}: {details[:1800]}"
                    ) from exc

                if attempt >= MAX_RETRIES:
                    raise RuntimeError(
                        f"Gemini HTTP {exc.code} after retries: "
                        f"{details[:1800]}"
                    ) from exc

                delay = 10 * (attempt + 1)
                retry = re.search(r'"retryDelay"\s*:\s*"(\d+)s"', details)
                if retry:
                    delay = min(int(retry.group(1)), 90)

                print(
                    f"[!] Gemini HTTP {exc.code}; "
                    f"retrying in {delay} seconds..."
                )
                time.sleep(delay)

        if not report or not is_complete_html(report):
            raise RuntimeError("A complete HTML report was not produced.")

        output.write_text(report, encoding="utf-8")
        print("[+] AI-generated report created successfully.")
        print(f"[+] Report: {output.resolve()}")
        print(f"[+] Size: {output.stat().st_size:,} bytes")
        return 0

    except Exception as exc:
        reason = str(exc)
        print("[!] Gemini AI report generation failed.")
        print(f"[!] Reason: {reason}")
        print("[+] Creating a labelled fallback report...")

        fallback = fallback_html(target, evidence, reason)
        output.write_text(fallback, encoding="utf-8")

        print("[!] Fallback report is NOT AI-generated.")
        print(f"[+] Report: {output.resolve()}")
        print(f"[+] Size: {output.stat().st_size:,} bytes")
        return 1


if __name__ == "__main__":
    sys.exit(main())
